  let language = 'zh-CN'
  try { if (localStorage.getItem(STORAGE_KEY) === 'en') language = 'en' } catch { /* Storage may be disabled. */ }

  function tr(key, ...values) {
    const text = language === 'en' && Object.hasOwn(EN, key) ? EN[key] : String(key)
    return text.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index]) : match)
  }

  // Only explicit error surfaces use this lookup; user messages never pass through it.
  const reverse = new Map(Object.entries(EN).map(([key, value]) => [value, key]))
  const messagePatterns = Object.entries(EN).flatMap(([key, english]) => {
    if (!key.includes('{0}') || key.startsWith('{')) return []
    return [key, english].map((template) => {
      const indexes = []
      const parts = template.split(/(\{\d+\})/g).map((part) => {
        if (/^\{\d+\}$/.test(part)) { indexes.push(Number(part.slice(1, -1))); return '([\\s\\S]*?)' }
        return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
      })
      return { key, indexes, pattern: new RegExp('^' + parts.join('') + '$') }
    })
  })
  function message(value) {
    const text = String(value ?? '')
    if (Object.hasOwn(EN, text)) return tr(text)
    if (reverse.has(text)) return tr(reverse.get(text))
    for (const { key, indexes, pattern } of messagePatterns) {
      const match = pattern.exec(text)
      if (!match) continue
      const values = []
      indexes.forEach((index, i) => { values[index] = match[i + 1] })
      return tr(key, ...values)
    }
    return text
  }

  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = tr(el.dataset.i18n) })
    for (const attr of ['title', 'aria-label', 'placeholder', 'data-placeholder', 'alt']) {
      root.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => el.setAttribute(attr, tr(el.getAttribute(`data-i18n-${attr}`))))
    }
    document.documentElement.lang = language
    document.title = tr('冰云画布 - 支持图片和视频')
    const button = document.getElementById('languageToggleBtn')
    if (button) {
      const label = language === 'en' ? '切换到中文' : 'Switch to English'
      button.title = label
      button.setAttribute('aria-label', label)
      button.setAttribute('lang', language === 'en' ? 'zh-CN' : 'en')
    }
  }

  function setLanguage(value, persist = true) {
    if (!['zh-CN', 'en'].includes(value)) return false
    if (persist) {
      try { localStorage.setItem(STORAGE_KEY, value) } catch { /* Switching still works in memory. */ }
    }
    if (language === value) return true
    language = value
    apply()
    window.dispatchEvent(new CustomEvent('bycanvas:languagechange', { detail: { language } }))
    return true
  }

  window.ByCanvasI18n = { tr, message, apply, setLanguage, get language() { return language }, keys: Object.keys(EN) }
  window.tr = tr
  document.documentElement.lang = language
  document.title = tr('冰云画布 - 支持图片和视频')
  document.addEventListener('DOMContentLoaded', () => apply())
  window.addEventListener('storage', (event) => {
    if (event.key === STORAGE_KEY || event.key === null) setLanguage(event.newValue === 'en' ? 'en' : 'zh-CN', false)
  })
